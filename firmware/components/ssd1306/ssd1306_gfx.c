void ssd1306_clear(ssd1306_t *d) { memset(d->fb, 0, sizeof(d->fb)); }

void ssd1306_pixel(ssd1306_t *d, int x, int y, bool on) {
    if (x < 0 || y < 0 || x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;
    uint8_t *b = &d->fb[(y / 8) * SSD1306_WIDTH + x];
    if (on) *b |= (uint8_t)(1u << (y % 8));
    else *b &= (uint8_t)~(1u << (y % 8));
}

void ssd1306_hline(ssd1306_t *d, int x, int y, int w) {
    for (int i = 0; i < w; i++) ssd1306_pixel(d, x + i, y, true);
}

void ssd1306_line(ssd1306_t *d, int x0, int y0, int x1, int y1) {  // Bresenham
    int dx = abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    for (;;) {
        ssd1306_pixel(d, x0, y0, true);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void ssd1306_rect(ssd1306_t *d, int x, int y, int w, int h, bool fill) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            if (fill || j == 0 || j == h - 1 || i == 0 || i == w - 1) ssd1306_pixel(d, x + i, y + j, true);
}

void ssd1306_invert(ssd1306_t *d, int x, int y, int w, int h) {
    for (int j = y; j < y + h; j++)
        for (int i = x; i < x + w; i++) {
            if (i < 0 || j < 0 || i >= SSD1306_WIDTH || j >= SSD1306_HEIGHT) continue;
            d->fb[(j / 8) * SSD1306_WIDTH + i] ^= (uint8_t)(1u << (j % 8));
        }
}

int ssd1306_text(ssd1306_t *d, int x, int y, const char *s, int scale) {
    if (scale < 1) scale = 1;
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c < 0x20 || c > 0x7E) c = '?';
        const uint8_t *g = kFont5x7[c - 0x20];
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 8; row++)
                if (g[col] & (1u << row))
                    for (int sy = 0; sy < scale; sy++)
                        for (int sx = 0; sx < scale; sx++)
                            ssd1306_pixel(d, x + col * scale + sx, y + row * scale + sy, true);
        x += 6 * scale;
    }
    return x;
}
